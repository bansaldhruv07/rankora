export function getResourceById(id) {
  return RESOURCES.find((resource) => resource.id === id)
}

export function getRelatedResources(resource, limit = 3) {
  const others = RESOURCES.filter((item) => item.id !== resource.id)
  const sameSubject = others.filter((item) => item.subject === resource.subject)
  const rest = others.filter((item) => item.subject !== resource.subject)
  return [...sameSubject, ...rest].slice(0, limit)
}

export function getResourceChapters(subject) {
  const chapters = RESOURCES.filter(
    (resource) => resource.type !== 'mock' && (!subject || resource.subject === subject),
  ).map((resource) => resource.chapter)
  return [...new Set(chapters)]
}