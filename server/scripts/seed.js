// Seeds the catalogue from the frontend's static data, generates placeholder PDFs into private
// storage, and optionally creates the first admin. Safe to re-run (upserts by slug / email).
//   ADMIN_EMAIL / ADMIN_PASSWORD  -> creates or promotes that account to admin
import bcrypt from 'bcryptjs'
import mongoose from 'mongoose'
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib'
import { PLANS } from '../../src/data/plans.js'
import { RESOURCES } from '../../src/data/resources.js'
import { assertEnv, env } from '../src/config/env.js'
import { Product } from '../src/models/Product.js'
import { User } from '../src/models/User.js'
import { toLatin } from '../src/services/watermark.js'
import { putObject } from '../src/services/storage.js'

assertEnv()
if (env.isProd && process.env.ALLOW_PROD_SEED !== 'true') {
  throw new Error('Refusing to seed in production without ALLOW_PROD_SEED=true')
}

async function samplePdf(resource) {
  const pdf = await PDFDocument.create()
  const font = await pdf.embedFont(StandardFonts.Helvetica)
  const page = pdf.addPage([595, 842])
  let y = 780
  const line = (text, size = 11) => {
    page.drawText(toLatin(text).slice(0, 90), { x: 50, y, size, font, color: rgb(0.1, 0.1, 0.1) })
    y -= size + 8
  }
  line(resource.title, 20)
  line(`${resource.subject} / ${resource.chapter}`, 11)
  y -= 10
  line(resource.summary, 10)
  y -= 10
  line('Contents', 14)
  resource.contents.forEach((item, i) => line(`${i + 1}. ${item}`))
  y -= 10
  line('Placeholder document generated by the seed script. Replace via the admin upload endpoint.', 9)
  return Buffer.from(await pdf.save())
}

await mongoose.connect(env.mongoUri)

let count = 0
for (const [index, r] of RESOURCES.entries()) {
  const doc = {
    slug: r.id,
    title: r.title,
    summary: r.summary,
    kind: 'note',
    subject: r.subject,
    chapter: r.chapter,
    type: r.type,
    difficulty: r.difficulty,
    length: r.length,
    pricePaise: r.price * 100,
    contents: r.contents,
    includes: r.includes,
    sample: r.sample,
    mockTestId: r.mockTestId,
    sortOrder: index,
    status: 'published',
  }
  const existing = await Product.findOne({ slug: r.id }).select('+file')
  if (r.type !== 'mock' && !existing?.file?.key) {
    const buffer = await samplePdf(r)
    const key = `notes/${r.id}.pdf`
    await putObject(key, buffer)
    doc.file = { key, originalName: `${r.id}.pdf`, size: buffer.length, uploadedAt: new Date() }
  }
  await Product.updateOne({ slug: r.id }, { $set: doc }, { upsert: true })
  count += 1
}

const premium = PLANS.find((p) => p.id === 'premium')
for (const [slug, title, planDays, price] of [
  ['premium-monthly', 'Rankora Premium (Monthly)', 30, premium.price.monthly],
  ['premium-yearly', 'Rankora Premium (Yearly)', 365, premium.price.yearly],
]) {
  await Product.updateOne(
    { slug },
    { $set: { slug, title, summary: premium.blurb, kind: 'plan', type: 'plan', planDays, pricePaise: price * 100, status: 'published' } },
    { upsert: true },
  )
}
console.log(`Seeded ${count} resources and 2 plans`)

if (process.env.ADMIN_EMAIL && process.env.ADMIN_PASSWORD) {
  const email = process.env.ADMIN_EMAIL.toLowerCase()
  const passwordHash = await bcrypt.hash(process.env.ADMIN_PASSWORD, env.bcryptRounds)
  await User.updateOne({ email }, { $set: { role: 'admin', passwordHash }, $setOnInsert: { name: 'Admin', email } }, { upsert: true })
  console.log(`Admin ready: ${email}`)
}

await mongoose.disconnect()
